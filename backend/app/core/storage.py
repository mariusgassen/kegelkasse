"""Where uploaded files live: the local uploads volume or an S3-compatible bucket (e.g. Garage).

Every stored file is addressed by a *key* such as ``media/media_3_<hex>.jpg``. The public URL is
always ``/uploads/<key>`` and the app itself serves it (``api/v1/media.py``), whichever backend is
active, so URLs saved in the database (``logo_url``, ``media_url``, ``user.avatar``) never change
when a club moves from the volume to a bucket.

With ``MEDIA_STORAGE=s3`` new files are written to the bucket only. Reads fall back to the local
volume when a key is not in the bucket yet, so files that ``scripts/migrate_media_to_s3.py`` has
not copied keep working until the migration has been verified.
"""
from __future__ import annotations

import logging
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Iterator, Optional

from core.config import settings

logger = logging.getLogger(__name__)

URL_PREFIX = "/uploads/"
# Keys are generated by the app (prefix folder + uuid/hash filename); anything else is refused so a
# request path can never reach outside the uploads area.
_KEY_RE = re.compile(r"^(?:media|logos|avatars|thumbs/\d{2,4})/[A-Za-z0-9][A-Za-z0-9_.-]*$")


def is_valid_key(key: str) -> bool:
    return bool(_KEY_RE.match(key)) and ".." not in key


def key_from_url(url: Optional[str]) -> Optional[str]:
    """``/uploads/logos/x.png`` → ``logos/x.png``; ``None`` for anything that is not a stored file."""
    if not url or not url.startswith(URL_PREFIX):
        return None
    key = url[len(URL_PREFIX):]
    return key if is_valid_key(key) else None


def url_for_key(key: str) -> str:
    return URL_PREFIX + key


@dataclass
class StoredObject:
    body: Iterator[bytes]
    size: Optional[int]
    content_type: Optional[str]
    etag: Optional[str] = None


class LocalStorage:
    name = "local"

    def __init__(self, root: Path):
        self.root = Path(root)

    def _path(self, key: str) -> Path:
        if not is_valid_key(key):
            raise ValueError(f"invalid storage key: {key!r}")
        return self.root / key

    def put(self, key: str, data: bytes, content_type: str) -> None:
        p = self._path(key)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)

    def size(self, key: str) -> Optional[int]:
        p = self._path(key)
        return p.stat().st_size if p.is_file() else None

    def read_bytes(self, key: str) -> Optional[bytes]:
        p = self._path(key)
        return p.read_bytes() if p.is_file() else None

    def open(self, key: str) -> Optional[StoredObject]:
        p = self._path(key)
        if not p.is_file():
            return None

        def _iter() -> Iterator[bytes]:
            with p.open("rb") as fh:
                while chunk := fh.read(64 * 1024):
                    yield chunk

        return StoredObject(body=_iter(), size=p.stat().st_size, content_type=None)

    def delete(self, key: str) -> None:
        try:
            self._path(key).unlink(missing_ok=True)
        except (OSError, ValueError):
            logger.warning("Could not delete local file %s", key)

    def iter_keys(self) -> Iterator[str]:
        if not self.root.is_dir():
            return
        for folder in ("media", "logos", "avatars"):
            d = self.root / folder
            if not d.is_dir():
                continue
            for p in sorted(d.iterdir()):
                key = f"{folder}/{p.name}"
                if p.is_file() and is_valid_key(key):
                    yield key


def _is_not_found(exc: Exception) -> bool:
    code = str(getattr(exc, "response", {}).get("Error", {}).get("Code", ""))
    return code in {"404", "NoSuchKey", "NotFound"}


class S3Storage:
    """S3-compatible bucket. ``client`` is a boto3 S3 client (injectable for tests)."""

    name = "s3"

    def __init__(self, client, bucket: str, fallback: Optional[LocalStorage] = None):
        self.client = client
        self.bucket = bucket
        self.fallback = fallback

    def put(self, key: str, data: bytes, content_type: str) -> None:
        if not is_valid_key(key):
            raise ValueError(f"invalid storage key: {key!r}")
        self.client.put_object(Bucket=self.bucket, Key=key, Body=data, ContentType=content_type)

    def size(self, key: str) -> Optional[int]:
        """Size of the object in the bucket (no fallback — used to verify the migration)."""
        try:
            head = self.client.head_object(Bucket=self.bucket, Key=key)
        except Exception as exc:
            if _is_not_found(exc):
                return None
            raise
        return int(head["ContentLength"])

    def read_bytes(self, key: str) -> Optional[bytes]:
        obj = self._get(key)
        return b"".join(obj.body) if obj else None

    def _get(self, key: str) -> Optional[StoredObject]:
        try:
            resp = self.client.get_object(Bucket=self.bucket, Key=key)
        except Exception as exc:
            if _is_not_found(exc):
                return None
            raise
        body = resp["Body"]
        return StoredObject(
            body=body.iter_chunks(64 * 1024) if hasattr(body, "iter_chunks") else iter([body.read()]),
            size=resp.get("ContentLength"),
            content_type=resp.get("ContentType"),
            etag=resp.get("ETag"),
        )

    def open(self, key: str) -> Optional[StoredObject]:
        if not is_valid_key(key):
            return None
        obj = self._get(key)
        if obj is None and self.fallback is not None:
            obj = self.fallback.open(key)
        return obj

    def delete(self, key: str) -> None:
        if not is_valid_key(key):
            return
        try:
            self.client.delete_object(Bucket=self.bucket, Key=key)
        except Exception:
            logger.warning("Could not delete S3 object %s", key, exc_info=True)
        # A not-yet-migrated copy on the volume would otherwise resurface through the fallback.
        if self.fallback is not None:
            self.fallback.delete(key)


def build_s3_client():
    import boto3
    from botocore.config import Config

    return boto3.client(
        "s3",
        endpoint_url=settings.MEDIA_S3_ENDPOINT_URL or None,
        region_name=settings.MEDIA_S3_REGION,
        aws_access_key_id=settings.MEDIA_S3_ACCESS_KEY_ID or None,
        aws_secret_access_key=settings.MEDIA_S3_SECRET_ACCESS_KEY or None,
        config=Config(
            signature_version="s3v4",
            s3={"addressing_style": "path" if settings.MEDIA_S3_FORCE_PATH_STYLE else "auto"},
        ),
    )


_storage = None


def local_storage() -> LocalStorage:
    return LocalStorage(Path(settings.UPLOADS_DIR))


def get_storage():
    global _storage
    if _storage is None:
        if settings.MEDIA_STORAGE.lower() == "s3":
            if not settings.MEDIA_S3_BUCKET:
                raise RuntimeError("MEDIA_STORAGE=s3 requires MEDIA_S3_BUCKET")
            _storage = S3Storage(build_s3_client(), settings.MEDIA_S3_BUCKET, fallback=local_storage())
        else:
            _storage = local_storage()
        logger.info("Media storage backend: %s", _storage.name)
    return _storage


def set_storage(storage) -> None:
    """Replace the active backend (tests)."""
    global _storage
    _storage = storage
